 id text primary key,
 turma text not null check(turma in ('3º1','3º2')),
 nome text not null,
 unique(turma,nome)
);
create table public.permutacao_entregas (
 id uuid primary key,
 aluno_id text not null unique references public.permutacao_alunos(id),
 alternativas text[] not null,
 acertos integer not null check(acertos between 0 and 5),
 enviado_em timestamptz not null default now(),
 check(array_ndims(alternativas)=1 and array_length(alternativas,1)=5 and array_lower(alternativas,1)=1 and alternativas <@ array['A','B','C','D']::text[] and array_position(alternativas,null) is null)
);
